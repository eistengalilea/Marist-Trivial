/** Mazos de la partida: una baraja por color con las preguntas aún sin salir. */
export type QuestionDecks = Record<CategoryColorId, TriviaQuestion[]>;

/** Copia barajada (Fisher–Yates) de una lista. */
function shuffled<T>(items: readonly T[]): T[] {
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/**
 * Baraja todas las categorías al empezar una partida. Cada partida tiene así
 * una secuencia de preguntas distinta.
 */
export function createQuestionDecks(): QuestionDecks {
  const decks = {} as QuestionDecks;
  for (const color of Object.keys(QUESTIONS_BY_COLOR) as CategoryColorId[]) {
    decks[color] = shuffled(QUESTIONS_BY_COLOR[color]);
  }
  return decks;
}

