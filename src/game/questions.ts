/** Índice por color construido una sola vez. */
const QUESTIONS_BY_COLOR: Record<CategoryColorId, readonly TriviaQuestion[]> = (() => {
  const index: Record<CategoryColorId, TriviaQuestion[]> = {
    blue: [],
    pink: [],
    yellow: [],
    purple: [],
    green: [],
    orange: [],
  };
  for (const q of QUESTION_BANK) index[q.color].push(q);
  return index;
})();

/** Mazos de la partida: una baraja por color con las preguntas aún sin salir. */
export type QuestionDecks = Record<CategoryColorId, TriviaQuestion[]>;

/** Copia barajada (Fisher–Yates) de una lista. */
function shuffled<T>(items: readonly T[]): T[] {
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/**
 * Baraja todas las categorías al empezar una partida. Cada partida tiene así
 * una secuencia de preguntas distinta.
 */
export function createQuestionDecks(): QuestionDecks {
  const decks = {} as QuestionDecks;
  for (const color of Object.keys(QUESTIONS_BY_COLOR) as CategoryColorId[]) {
    decks[color] = shuffled(QUESTIONS_BY_COLOR[color]);
  }
  return decks;
}

/**
 * Saca la siguiente pregunta del mazo de un color y la retira, de modo que no
 * se repite en la partida. Dentro del orden barajado se prefiere la primera
 * pregunta de la dificultad elegida; si ya no quedan de esa dificultad, sale la
 * siguiente del mazo. Solo cuando las 20 preguntas de un color han salido se
 * vuelve a barajar ese color (evitando repetir justo la última).
 */
export function drawQuestionFromDeck(
  decks: QuestionDecks,
  color: CategoryColorId,
  difficulty: DifficultyLevel,
): TriviaQuestion {
  const deck = decks[color];
  const preferred = deck.findIndex((q) => q.difficulty === difficulty);
  const [question] = deck.splice(preferred === -1 ? 0 : preferred, 1);

  if (deck.length === 0) {
    // Color agotado: se vuelve a barajar sin que la próxima repita esta misma.
    const next = shuffled(QUESTIONS_BY_COLOR[color]);
    if (next.length > 1 && next[0].id === question.id) next.push(next.shift()!);
    decks[color] = next;
  }
  return question;
}
